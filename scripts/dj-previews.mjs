import { djProfiles, djProfile } from "../lib/djs.js";

export const mainDjRoutes = ["/", "/stations/1"];
export function djPreviewFile(path, params) {
  const route = path.replace(/\/+$/, "") || "/";
  const values = params.getAll("dj");
  const profile = values.length === 1 && djProfile(values[0]);
  if (!mainDjRoutes.includes(route) || !profile) return null;
  return `dj-previews/${profile.id}/${route === "/" ? "main" : "station-1"}.html`;
}

// Match URLSearchParams' percent-decoded keys/values without interpolating any
// request value into a filesystem path. Repeated keys always use station cards.
const encoded = (text) =>
  [...text]
    .map((char) => {
      const hex = char
        .charCodeAt(0)
        .toString(16)
        .replace(/[a-f]/g, (c) => `[${c}${c.toUpperCase()}]`);
      return `(?:${char}|%${hex})`;
    })
    .join("");
export function djNginxMaps(base = "/player/") {
  const key = encoded("dj");
  const lines = [
    "# Generated by scripts/build.mjs. Install in nginx http context.",
    "map $args $dnb_player_dj {",
    '    default "";',
    `    "~(?:^|&)${key}(?:=[^&]*)?(?:&[^&]*)*&${key}(?:=|&|$)" "";`,
    ...Object.keys(djProfiles).map(
      (id) => `    "~(?:^|&)${key}=${encoded(id)}(?:&|$)" ${id};`,
    ),
    "}",
    "map $uri:$dnb_player_dj $dnb_player_dj_page {",
    "    default $uri;",
    ...mainDjRoutes.flatMap((route) =>
      Object.keys(djProfiles).flatMap((id) => {
        const path = base + route.slice(1);
        const paths = route === "/" ? [path] : [path, path + "/"];
        return paths.map(
          (url) =>
            `    ${url}:${id} ${base}${djPreviewFile(route, new URLSearchParams({ dj: id }))};`,
        );
      }),
    ),
    "}",
    "",
  ];
  return lines.join("\n");
}
